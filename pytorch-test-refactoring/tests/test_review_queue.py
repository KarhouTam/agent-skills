def _fake_gh_factory(
    calls, *, patch=_PATCH, state="OPEN", head="oid", login="other-login"
):
    def fake_gh(*args):
        calls.append(args)
        joined = " ".join(args)
        if joined.startswith("pr diff"):
            return patch
        if joined.startswith("pr view"):
            return json.dumps(
                {
                    "number": 7,
                    "title": "Decouple tests",
                    "author": {"login": "author-login"},
                    "state": state,
                    "url": "https://github.com/pytorch/pytorch/pull/7",
                    "headRefOid": head,
                    "files": [{"path": "test/test_anchor.py"}],
                }
            )
        if joined.startswith("api user"):
            return login + "\n"
        if "--method POST" in joined and args[1] == "--method":
            # args: api --method POST repos/... --input FILE
            payload = json.loads(Path(args[-1]).read_text())
            calls.append(("PAYLOAD", payload))
            return json.dumps(
                {
                    "id": 11,
                    "state": "REQUEST_CHANGES",
                    "html_url": "https://github.com/pytorch/pytorch/pull/7/reviews/11",
                }
            )
        raise AssertionError(f"unexpected gh call: {args}")

    return fake_gh


def test_publish_posts_payload_from_ledger(tmp_path, monkeypatch):
    ledger, _, _ = _drafted(tmp_path, monkeypatch, findings=[_finding()])
    calls = []
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(review_queue, "_run_gh", _fake_gh_factory(calls))
    monkeypatch.setattr(review_queue, "gh_pr_info", lambda n: {
        "state": "OPEN", "head_oid": "oid", "url": "u",
    })
    _write_pending(
        tmp_path,
        [
            "https://github.com/pytorch/pytorch/pull/7",
            "https://github.com/pytorch/pytorch/pull/8",
        ],
    )
    out = review_queue.publish_from_ledger(tmp_path)

    assert out["status"] == "done" and out["posted"] == 1
    outcome = out["outcomes"][0]
    assert outcome["review_url"].endswith("pull/7/reviews/11")
    assert outcome["comments"] == 1
    payload = next(c[1] for c in calls if c and c[0] == "PAYLOAD")
    assert payload["event"] == "COMMENT", "the machine never requests changes"
    assert payload["commit_id"] == "oid"
    assert payload["body"].endswith(REVIEW_TAIL)
    assert payload["comments"] == [
        {
            "path": "test/test_anchor.py",
            "line": 12,
            "side": "RIGHT",
            "body": "Use @onlyAccelerator instead of @onlyCUDA.",
        }
    ]
    # archive + pending + ledger consumption; the semantic verdict survives
    # in the archive so the re-admit watch keeps watching for fixes
    archive = review_queue.load_archive()
    assert archive["records"][0]["review_url"].endswith("reviews/11")
    assert archive["records"][0]["verdict"] == "changes_requested"
    assert review_queue.load_pending() == [
        "https://github.com/pytorch/pytorch/pull/8"
    ]
    assert not Path(review_queue.pending_publication_path(tmp_path)).exists()


