def test_review_ops_subagent_waves(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(review_queue, "select_pending", lambda limit=10: _select_result(6))
    monkeypatch.setattr(
        review_queue,
        "write_pre_pass",
        lambda item,
        workspace=None: {
            "ran": True,
            "findings": [],
            "lint_gate": {"ran": True, "skipped": False, "reason": "", "findings": []},
        },
    )
    drafted = {}

    def fake_draft(reviewed, not_applicable, workspace, date_str=None):
        drafted["reviewed"] = [r.pr_number for r in reviewed]
        return {
            "ledger_path": str(Path(workspace) / "pending_publication.md"),
            "ledger_written": True,
            "entry_count": len(reviewed),
            "comment_count": 0,
            "na_count": 0,
        }

    monkeypatch.setattr(review_queue, "draft_ledger", fake_draft)
    ops = ReviewOps(limit=10, supports_delegated_agents=True)
    assert ops.mode == "subagents"
    ops.run()
    assert ops.state.phase == "review"
    assert len(ops.state.in_flight) == 4
    assert ops.state.signal.value == "spawn_parallel"
    tasks = ops.get_pending_tasks()
    assert [t.agent_name for t in tasks] == [
        "reviewer_pr_1000",
        "reviewer_pr_1001",
        "reviewer_pr_1002",
        "reviewer_pr_1003",
    ]

    for task in tasks:
        pr = task.context["pr_number"]
        ops.feed_reviewer_result({"pr_number": pr, "success": True, "all_clear": True})
        ops.run()
    assert len(ops.state.in_flight) == 2
    assert ops.state.signal.value == "spawn_parallel"

    for task in ops.get_pending_tasks():
        pr = task.context["pr_number"]
        ops.feed_reviewer_result({"pr_number": pr, "success": True, "all_clear": True})
        ops.run()
    assert ops.state.phase == "done"
    assert sorted(drafted["reviewed"]) == [1000, 1001, 1002, 1003, 1004, 1005]
    ops.finalize()
    assert not (tmp_path / "agent_space" / "pr_reviews" / "flow_state.json").exists()
