def test_user_edits_change_what_publishes(tmp_path, monkeypatch):
    ledger, text, _ = _drafted(
        tmp_path, monkeypatch, findings=[_finding()]
    )
    # The machine drafted COMMENT; a deliberate user edit is the only way a
    # REQUEST_CHANGES event exists. Here the user upgrades and also deletes
    # the inline block.
    edited = text.replace("event: COMMENT", "event: REQUEST_CHANGES")
    edited = edited.replace(
        "```comment\npath: test/test_anchor.py\nline: 12\n"
        "body: Use @onlyAccelerator instead of @onlyCUDA.\n```\n",
        "",
    )
    Path(ledger).write_text(edited)
    _, entries = review_queue.parse_ledger(edited)
    entry = entries[0]
    assert entry.event == "REQUEST_CHANGES" and entry.comments == []
    # a user-added inline block is picked up the same way
    with_block = edited.replace(
        "body:\n```body",
        "inline:\n```comment\npath: test/test_anchor.py\nline: 13\n"
        "body: user-added remark\n```\nbody:\n```body",
    )
    _, entries2 = review_queue.parse_ledger(with_block)
    assert entries2[0].comments[0].body == "user-added remark"


def test_fences_survive_reviewer_fences(tmp_path, monkeypatch):
    # A body/inline line STARTING with ``` would break the block parser, so
    # the renderer strips such lines: an inline body that is only a fence
    # gets emptied (comment dropped), and a fence mid-line stays a literal
    # in the body list while the fenced body itself remains parseable.
    findings = [_finding(description="rely on prose", inline="```")]
    _, text, _ = _drafted(tmp_path, monkeypatch, findings=findings)
    date, entries = review_queue.parse_ledger(text)
    assert date == "2026-10-29" and entries[0].comments == []
    assert "inline:" not in text
    assert entries[0].body.endswith(REVIEW_TAIL)
    assert (
        "- [Blocker/code-quality] test/test_anchor.py:12: ```" in entries[0].body
    ), "mid-line fences stay literal (they cannot break the block)"


