def _finding(**overrides):
    base = {
        "severity": "Blocker",
        "category": "code-quality",
        "file": "test/test_anchor.py",
        "line_number": 12,
        "description": "@onlyCUDA should be @onlyAccelerator.",
        "inline": "Use @onlyAccelerator instead of @onlyCUDA.",
        "fix": "replace the decorator",
    }
    base.update(overrides)
    return base


_PATCH = (
    "diff --git a/test/test_anchor.py b/test/test_anchor.py\n"
    "--- a/test/test_anchor.py\n"
    "+++ b/test/test_anchor.py\n"
    "@@ -10,3 +10,4 @@\n"
    " context\n"
    "+added twelve\n"
    "+added thirteen\n"
)


def _drafted(tmp_path, monkeypatch, findings=None):
    monkeypatch.chdir(tmp_path)
    # draft_ledger receives `tmp_path` as its workspace, so the pre-pass diff
    # cache it reads sits at the workspace root (the same layout review_ops
    # uses, where workspace == agent_space/pr_reviews).
    (tmp_path / "pr_7_diff.patch").write_text(_PATCH)
    result = PrReviewResult(
        pr_number=7,
        title="Decouple tests",
        author="author-login",
        state="OPEN",
        head_oid="oid",
        all_clear=not findings,
        reviewed_files=["test/test_anchor.py"],
        findings=findings or [],
        summary="Moves tests into an accelerator-agnostic class.",
    )
    out = review_queue.draft_ledger([result], [], tmp_path, date_str="2026-10-29")
    ledger = out["ledger_path"]
    assert out["ledger_written"] and out["entry_count"] == 1
    text = Path(ledger).read_text()
    return ledger, text, result


def test_draft_ledger_writes_body_note_and_inline(tmp_path, monkeypatch):
    ledger, text, _ = _drafted(
        tmp_path, monkeypatch, findings=[_finding(), _finding(line_number=99)]
    )
    assert "## PR #7 — Decouple tests — @author-login" in text
    # Publication is always a COMMENT event, even with a Blocker finding.
    assert "event: COMMENT" in text
    assert "event: REQUEST_CHANGES" not in text
    assert "verdict: changes_requested" in text, "semantic verdict stays visible"
    assert (
        "_Generated by my agent. Reviewed by the user._" in text
    ), "the note is part of the body and the user may delete it there"
    assert "@claude double check" not in text, "no handing-off line"
    # the anchored finding became an inline comment; the stray one did not
    body_comment = 'body: Use @onlyAccelerator instead of @onlyCUDA.'
    assert "path: test/test_anchor.py\nline: 12" in text
    assert body_comment in text
    assert "line: 99" not in text
    # the unanchored finding is still listed in the body
    assert "[Blocker/code-quality] test/test_anchor.py:99:" in text
    # header keys survive parse
    date, entries = review_queue.parse_ledger(text)
    assert date == "2026-10-29"
    assert entries[0].event == "COMMENT"
    assert len(entries[0].comments) == 1


