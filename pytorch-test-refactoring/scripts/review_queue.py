"""Deterministic PR review queue logic for the review-queue sidecar.

Handles the mechanical parts of the daily batch review: loading the pending
PR list, classifying PRs via `gh` (open/merged/closed, test-file changes),
running the mandatory TEST_LINTER pre-pass, rendering the pending-publication
ledger, and — after the user approves that ledger — submitting one GitHub
review per PR section. No AI logic here — reviews are driven by
agent/prompts/reviewer.md (Claude sub-agent) or
agent/prompts/reviewer_batch.md (Codex inline executor), and nothing reaches
GitHub before the user has edited and approved
`agent_space/pr_reviews/pending_publication.md`.
"""

from __future__ import annotations

import json
import re
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from state import PrReviewItem, PrReviewResult
from scripts.test_linter_gate import run_gate
from scripts.verify import added_line_map, pre_pass_patch
from utils import (
    PR_QUEUE_FILE,
    PR_REVIEW_TEST_PREFIXES,
    PR_REVIEW_WORKSPACE_ROOT,
    PR_REVIEWED_ARCHIVE_FILE,
    run_gh as _run_gh,
)

REPO = "pytorch/pytorch"

_PR_URL_RE = re.compile(r"pull[s]?/(\d+)")

# The pending-publication ledger: the single source of truth for what gets
# posted. After every review batch the machine stops here; only an explicit
# user approval (and then `--review-queue --publish`) submits anything.
PENDING_PUBLICATION_FILE = "pending_publication.md"
PENDING_PUBLICATION_HEADER = "# Pending PR Review Publication — {date}\n"
HOW_TO_EDIT = """<!--
How to edit (the agent reads this file back and posts it as-is):
- Each `## PR #n` section becomes one GitHub review submitted as the gh
  account the user is logged in as.
- `event:` is drafted as COMMENT: the machine never requests changes on its
  own. Flip it to REQUEST_CHANGES only by deliberate choice (never APPROVE).
  `verdict:` is informational (the severity mapping; it drives the archive's
  re-review-on-new-commit watch), not part of the payload.
- The ```body block is the review summary; it is posted verbatim. The
  `_Generated by my agent. Reviewed by the user._` line inside it is part of
  the body and may be edited or removed like anything else.
- Each ```comment block becomes one inline comment anchored to `path:` and
  `line:`. Edit any key freely; delete a block to drop that inline comment;
  add blocks for extra inline comments.
- Delete a whole PR section to skip that PR (it stays in the pending list
  and is re-reviewed in the next batch).
- Sections are posted against the PR's `head:` commit; the publish step
  skips a section whose PR has changed underneath (head moved / not open).
-->
"""

DIFF_CACHE_FILE = "pr_{}_diff.patch"
_PRE_PASS_FILE = "pr_{}_prepass.json"


@dataclass
class SelectResult:
    """Partition of one selection pass over the pending list."""

    review_queue: list[PrReviewItem] = field(default_factory=list)
    not_applicable: list[PrReviewItem] = field(default_factory=list)
    failed: list[PrReviewItem] = field(default_factory=list)


# ── gh helpers ──────────────────────────────────────────────────────


def gh_pr_info(pr_number: int) -> dict | None:
    """Fetch PR metadata via `gh pr view`. Returns None on any failure."""
    try:
        out = _run_gh(
            "pr",
            "view",
            str(pr_number),
            "--repo",
            REPO,
            "--json",
            "number,title,author,state,url,files,headRefOid",
        )
        data = json.loads(out)
    except (subprocess.CalledProcessError, json.JSONDecodeError):
        return None
    author = (data.get("author") or {}) or {}
    files = data.get("files") or []
    return {
        "number": data.get("number", pr_number),
        "title": data.get("title", ""),
        "author": author.get("login", ""),
        "state": data.get("state", ""),
        "url": data.get("url", f"https://github.com/{REPO}/pull/{pr_number}"),
        "head_oid": data.get("headRefOid", "") or "",
        "paths": [f.get("path", "") for f in files],
    }


def has_test_changes(paths: list[str]) -> bool:
    """True if any changed path is a test file (test/** or torch/testing/**)."""
    return any(p.startswith(PR_REVIEW_TEST_PREFIXES) for p in paths)


# ── pending list ────────────────────────────────────────────────────


def parse_pr_url(url: str) -> int | None:
    """Extract the PR number from a GitHub PR URL, or None."""
    m = _PR_URL_RE.search(url)
    if not m:
        return None
    try:
        return int(m.group(1))
    except ValueError:
        return None


def load_pending(path: Path | str | None = None) -> list[str]:
    """Load the pending PR URLs, deduped and in file order."""
    path = Path(path) if path else PR_QUEUE_FILE
    if not path.exists():
        return []
    urls: list[str] = []
    seen: set[str] = set()
    for raw in path.read_text(encoding="utf-8").splitlines():
        url = raw.strip()
        if not url:
            continue
        if url in seen:
            continue
        seen.add(url)
        urls.append(url)
    return urls


def save_pending(urls: list[str], path: Path | str | None = None) -> None:
    """Rewrite the pending list file (newline-terminated, deduped)."""
    path = Path(path) if path else PR_QUEUE_FILE
    seen: set[str] = set()
    lines: list[str] = []
    for url in urls:
        url = url.strip()
        if not url or url in seen:
            continue
        seen.add(url)
        lines.append(url)
    path.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")


_RE_ADMIT_MAX = 30


def readmitted_urls(workspace: Path | str | None = None) -> list[str]:
    """Archived PRs whose head moved since the review that asked them to iterate.

    Only records whose verdict was `changes_requested` are re-checked, and only
    the most recent `_RE_ADMIT_MAX` of them. A PR the author has not touched
    stays quiet; a PR the review asked to fix that then got a new commit
    returns to the queue. Without this the review verdict would fade and
    nothing would ever watch for the iteration.
    """
    archive = load_archive(
        Path(workspace) / PR_REVIEWED_ARCHIVE_FILE if workspace else None
    )
    records = [
        rec
        for rec in archive.get("records", [])
        if rec.get("verdict") == "changes_requested" and rec.get("pr_number")
    ][-_RE_ADMIT_MAX:]
    urls: list[str] = []
    for rec in records:
        info = gh_pr_info(rec["pr_number"])
        if info is None or info.get("state") != "OPEN":
            continue
        if info.get("head_oid") and info["head_oid"] != rec.get("head_oid", ""):
            urls.append(info["url"])
    return urls


def select_pending(
    limit: int = 10,
    pending_path: Path | str | None = None,
) -> SelectResult:
    """Classify pending PRs FIFO and select up to `limit` reviewable ones.

    - OPEN PRs with test-file changes → review_queue (up to `limit`).
    - merged/closed PRs or OPEN PRs without test-file changes →
      not_applicable (archived while drafting, never published anywhere).
    - PRs whose metadata could not be fetched → failed (stays pending,
      never published).
    Scanning stops once `limit` reviewable PRs are found; everything after
    stays pending untouched.
    """
    result = SelectResult()
    seen: set[str] = set()
    pending: list[str] = []
    for url in readmitted_urls() + load_pending(pending_path):
        if url in seen:
            continue
        seen.add(url)
        pending.append(url)
    for url in pending:
        if len(result.review_queue) >= limit:
            break
        pr_number = parse_pr_url(url)
        if not pr_number:
            result.failed.append(
                PrReviewItem(url=url, pr_number=0, status="failed", reason="bad_url")
            )
            continue
        info = gh_pr_info(pr_number)
        if info is None:
            result.failed.append(
                PrReviewItem(
                    url=url, pr_number=pr_number, status="failed", reason="fetch_failed"
                )
            )
            continue
        item = PrReviewItem(
            url=info["url"],
            pr_number=pr_number,
            title=info["title"],
            author=info["author"],
            state=info["state"],
            has_test_changes=has_test_changes(info["paths"]),
            head_oid=info.get("head_oid", ""),
        )
        if item.state != "OPEN":
            item.status = "na"
            item.reason = "merged/closed"
            result.not_applicable.append(item)
        elif not item.has_test_changes:
            item.status = "na"
            item.reason = "no_test_changes"
            result.not_applicable.append(item)
        else:
            result.review_queue.append(item)
    return result


# ── archive ─────────────────────────────────────────────────────────


def load_archive(path: Path | str | None = None) -> dict:
    """Load the processed-PR archive. Returns {'records': [], 'last_run': {}}."""
    path = Path(path) if path else PR_REVIEW_WORKSPACE_ROOT / PR_REVIEWED_ARCHIVE_FILE
    if not path.exists():
        return {"records": [], "last_run": {}}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {"records": [], "last_run": {}}
    if not isinstance(data, dict):
        return {"records": [], "last_run": {}}
    data.setdefault("records", [])
    data.setdefault("last_run", {})
    return data


def save_archive(archive: dict, path: Path | str | None = None) -> None:
    """Persist the processed-PR archive."""
    path = Path(path) if path else PR_REVIEW_WORKSPACE_ROOT / PR_REVIEWED_ARCHIVE_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(archive, indent=2, ensure_ascii=False), encoding="utf-8")


def _archive_record_common() -> dict:
    return {
        "url": "",
        "pr_number": 0,
        "title": "",
        "author": "",
        "state": "",
        "date": "",
        "review_url": "",
        "status": "reviewed",
        "reason": "",
        "verdict": "",
        "head_oid": "",
        "findings_count": 0,
        "all_clear": None,
        "summary": "",
    }


def archive_na(items: list[PrReviewItem], date_str: str | None = None) -> None:
    """Archive the not-applicable PRs of a batch and drop them from pending.

    Not-applicable PRs (merged/closed, no test changes) never receive any
    published comment, but they must leave the queue.
    """
    date_str = date_str or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    records: list[dict] = []
    for item in items:
        records.append(
            {
                **_archive_record_common(),
                "url": item.url,
                "pr_number": item.pr_number,
                "title": item.title,
                "author": item.author,
                "state": item.state,
                "date": date_str,
                "status": "na",
                "reason": item.reason,
                "head_oid": item.head_oid,
                "findings_count": 0,
                "all_clear": None,
                "summary": "",
            }
        )
    if not records:
        return
    archive_path = PR_REVIEW_WORKSPACE_ROOT / PR_REVIEWED_ARCHIVE_FILE
    archive = load_archive(archive_path)
    archive["records"].extend(records)
    archive["last_run"] = {"date": date_str, "ledger": PENDING_PUBLICATION_FILE}
    save_archive(archive, archive_path)
    remove = {i.pr_number for i in items}
    save_pending(
        [u for u in load_pending() if parse_pr_url(u) not in remove],
    )


# ── pre-pass ────────────────────────────────────────────────────────

# The machine-decidable criteria of II.12 and the walker over a diff's
# added lines are defined once, in scripts/verify.py (`pre_pass_patch`),
# which also runs them as the `review_mechanics` check of the 8-phase workflow.
# Nothing is redefined here, so the two entry points cannot drift apart.
# The mandatory TEST_LINTER gate (the fifth mechanized source) runs right
# beside them, vendored from pytorch/pytorch at a pinned SHA in
# scripts/test_linter_gate.py.


def _save_patch(root: Path, pr_number: int, patch: str) -> None:
    """Cache the diff the review is based on, for the draft step."""
    path = root / DIFF_CACHE_FILE.format(pr_number)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(patch, encoding="utf-8")


def write_pre_pass(item: PrReviewItem, workspace: Path | str | None = None) -> dict:
    """Run the deterministic pre-pass over one PR's diff and write it.

    Writes `pr_<number>_prepass.json`, which the reviewer prompt reads. It
    carries the four mechanized criteria over the added lines, plus
    `lint_gate`: the mandatory TEST_LINTER gate over the PR's head test
    files. A failed diff fetch is recorded as `ran: false` rather than
    raising; the caller must treat PRs with `ran: false` (either key) as
    failing this run — the review, and especially the gate, is mandatory.
    """
    root = Path(workspace) if workspace else PR_REVIEW_WORKSPACE_ROOT
    path = root / _PRE_PASS_FILE.format(item.pr_number)
    try:
        patch = _run_gh(
            "pr",
            "diff",
            str(item.pr_number),
            "--repo",
            REPO,
        )
    except subprocess.CalledProcessError:
        data: dict = {
            "ran": False,
            "reason": "diff_failed",
            "findings": [],
            "lint_gate": {
                "ran": False,
                "skipped": False,
                "reason": "diff_failed",
                "findings": [],
            },
        }
    else:
        _save_patch(root, item.pr_number, patch)
        data = {
            "ran": True,
            "findings": pre_pass_patch(patch),
            "lint_gate": run_gate(item.pr_number, item.head_oid, patch, root),
        }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    return data


# ── verdict ─────────────────────────────────────────────────────────


def verdict_of(result: PrReviewResult) -> str:
    """Per-PR verdict: `changes_requested` iff any Blocker/Major finding.

    Mirror of the severity-to-verdict mapping of the review criteria (II.11):
    Blocker and Major both cross the boundary; Minor does not. A
    reviewer-supplied verdict wins, so a manual override survives.
    """
    if result.verdict:
        return result.verdict
    if result.all_clear and not any(
        f.severity in ("Blocker", "Major") for f in result.findings
    ):
        return "ready_for_human_review"
    return (
        "changes_requested"
        if any(f.severity in ("Blocker", "Major") for f in result.findings)
        else "ready_for_human_review"
    )


# ── publication ledger ──────────────────────────────────────────────

REVIEW_NOTE = "_Generated by my agent. Reviewed by the user._"

_CJK_RE = re.compile(r"[\u3400-\u9fff\uf900-\ufaff]")


def _has_cjk(text: str) -> bool:
    """True when the text carries CJK characters (publication is English)."""
    return bool(_CJK_RE.search(text))


def _fence_safe(text: str) -> str:
    """Strip lines that a fenced block cannot carry so parsing stays exact."""
    return "\n".join(
        line for line in text.splitlines() if not line.lstrip().startswith("```")
    )


def _finding_oneliner(finding) -> str:
    """The terse claim of a finding; the `inline` field when written."""
    return (finding.inline or finding.description or "").strip()


def _render_body(result: PrReviewResult) -> str:
    """The English review body: summary, terse findings, and the note."""
    summary = (result.summary or "").strip()
    if not summary:
        files = ", ".join(result.reviewed_files) if result.reviewed_files else "the changed test files"
        summary = f"Diff-based review of {files} against the test-decoupling standards."
    lines = [summary, ""]
    if result.findings and not (result.all_clear and not result.findings):
        lines.append(f"Findings ({len(result.findings)}):")
        for f in result.findings:
            anchor = f"{f.file}:{f.line_number}" if f.file else "(file level)"
            lines.append(f"- [{f.severity}/{f.category}] {anchor}: {_finding_oneliner(f)}")
            if f.fix and f.fix.strip() and f.fix.strip() != _finding_oneliner(f):
                lines.append(f"  fix: {f.fix.strip()}")
    else:
        lines.append("No blocking issues found; ready for human review.")
    lines += ["", REVIEW_NOTE]
    return _fence_safe("\n".join(lines))


@dataclass
class LedgerComment:
    """One inline comment block of the pending-publication ledger."""

    path: str = ""
    line: int = 0
    body: str = ""


@dataclass
class LedgerEntry:
    """One PR section of the pending-publication ledger.

    `raw` keeps the section's exact original lines so an unparsed user edit
    survives a publish that consumes other sections around it. `verdict` is
    the semantic II.11 verdict (Blocker/Major ⇒ `changes_requested`); it is
    recorded in the archive and drives the re-review-on-new-commit watch.
    The published review EVENT is a separate thing: the machine drafts
    `COMMENT` only (see `_build_entries`).
    """

    pr_number: int
    title: str = ""
    author: str = ""
    url: str = ""
    head_oid: str = ""
    event: str = ""  # "REQUEST_CHANGES" | "COMMENT" | (invalid → publish error)
    verdict: str = ""  # "changes_requested" | "ready_for_human_review" | ""
    body: str = ""
    comments: list[LedgerComment] = field(default_factory=list)
    lang_warning: bool = False
    raw: str = ""


def _render_section(entry: LedgerEntry) -> str:
    """One PR section, exactly as the publish step later reads it back."""
    out = [
        f"## PR #{entry.pr_number} — {entry.title} — @{entry.author}",
        f"url: {entry.url}",
        f"head: {entry.head_oid}",
        f"event: {entry.event}",
        f"verdict: {entry.verdict}",
    ]
    if entry.lang_warning:
        out.append(
            "lang-note: contains non-English characters; the user is expected"
            " to translate or rewrite the text before publishing"
        )
    out.append("body:")
    out.append("```body")
    out.append(entry.body)
    out.append("```")
    if entry.comments:
        out.append("inline:")
        for c in entry.comments:
            out += [
                "```comment",
                f"path: {c.path}",
                f"line: {c.line}",
                f"body: {c.body}",
                "```",
            ]
    return "\n".join(out)


def _build_entries(reviewed: list[PrReviewResult], workspace: Path) -> list[LedgerEntry]:
    """Turn reviewer results into ledger entries, deciding inline anchors.

    Anchoring is validated against the diff the review actually ran on
    (cached by the pre-pass); a finding whose `file:line` is not an added
    line stays out of the inline set. `inline` one-liners carry the text;
    `description` is the fallback.
    """
    entries: list[LedgerEntry] = []
    for r in reviewed:
        patch_path = Path(workspace) / DIFF_CACHE_FILE.format(r.pr_number)
        try:
            patch = patch_path.read_text(encoding="utf-8")
        except OSError:
            try:
                patch = _run_gh("pr", "diff", str(r.pr_number), "--repo", REPO)
            except subprocess.CalledProcessError:
                patch = ""
        added = added_line_map(patch) if patch else {}
        comments: list[LedgerComment] = []
        for f in r.findings:
            anchored = (
                bool(f.file)
                and f.line_number > 0
                and f.line_number in added.get(f.file, set())
            )
            text = _fence_safe(_finding_oneliner(f)).strip()
            if anchored and text:
                comments.append(
                    LedgerComment(
                        path=f.file,
                        line=f.line_number,
                        body=text,
                    )
                )
        url = f"https://github.com/{REPO}/pull/{r.pr_number}"
        body = _render_body(r)
        entries.append(
            LedgerEntry(
                pr_number=r.pr_number,
                title=r.title,
                author=r.author,
                url=url,
                head_oid=r.head_oid,
                event=DEFAULT_REVIEW_EVENT,
                verdict=verdict_of(r),
                body=body,
                comments=comments,
                lang_warning=_has_cjk(body)
                or any(_has_cjk(c.body) for c in comments),
            )
        )
    return entries


# The machine drafts every published review as a plain COMMENT, whatever the
# findings say: the II.11 verdict is stated in the body and recorded in the
# archive (driving the re-admit watch), but a REQUEST_CHANGES event is only
# ever a deliberate user edit of the ledger's `event:` line.
DEFAULT_REVIEW_EVENT = "COMMENT"


def render_ledger(date_str: str, entries: list[LedgerEntry]) -> str:
    """The whole pending-publication document.

    A parsed section is re-emitted from its exact original lines
    (`entry.raw`); only freshly built entries are rendered.
    """
    parts = [PENDING_PUBLICATION_HEADER.format(date=date_str), HOW_TO_EDIT]
    for entry in entries:
        parts.append(entry.raw or _render_section(entry))
    return "\n\n".join(parts) + "\n"


def pending_publication_path(workspace: Path | str | None = None) -> Path:
    """Path of the pending-publication document (overridable for tests)."""
    ws = Path(workspace) if workspace else PR_REVIEW_WORKSPACE_ROOT
    return ws / PENDING_PUBLICATION_FILE


def draft_ledger(
    reviewed: list[PrReviewResult],
    not_applicable: list[PrReviewItem],
    workspace: Path | str | None = None,
    date_str: str | None = None,
) -> dict:
    """Write the pending-publication document and archive the NA PRs.

    This is where the review batch STOPS: nothing reaches GitHub until the
    user edits and approves the ledger and the publish step runs. Not
    applicable PRs (merged/closed, no test changes) are archived here since
    they never receive a published comment. Returns a summary for the
    orchestrator's JSON.
    """
    date_str = date_str or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    workspace = Path(workspace) if workspace else PR_REVIEW_WORKSPACE_ROOT
    workspace.mkdir(parents=True, exist_ok=True)
    archive_na(not_applicable, date_str)
    entries = _build_entries(reviewed, workspace)
    path = pending_publication_path(workspace)
    if entries:
        path.write_text(render_ledger(date_str, entries), encoding="utf-8")
    return {
        "ledger_path": str(path),
        "entry_count": len(entries),
        "ledger_written": bool(entries),
        "comment_count": sum(len(e.comments) for e in entries),
        "na_count": len(not_applicable),
    }


def _read_fence(lines: list[str], open_idx: int) -> tuple[str, int]:
    """Consume one fenced block opened at `open_idx` (a ``` line).

    Returns (content, index one past the closing fence). Content is
    everything before the closing fence; malformed blocks (no closer) run
    to the end of the file.
    """
    j = open_idx + 1
    content: list[str] = []
    while j < len(lines) and lines[j] != "```":
        content.append(lines[j])
        j += 1
    return "\n".join(content), j + 1


def _parse_comment_block(block: str) -> LedgerComment | None:
    """`path:` / `line:` / `body:` keys of one inline-comment block."""
    path = ""
    line_no = 0
    body_lines: list[str] = []
    for raw in block.splitlines():
        if raw.startswith("path:"):
            path = raw[len("path:") :].strip()
        elif raw.startswith("line:"):
            m = re.search(r"\d+", raw)
            line_no = int(m.group(0)) if m else 0
        elif raw.startswith("body:"):
            body_lines.append(raw[len("body:") :].lstrip())
        elif body_lines:
            body_lines.append(raw)  # a body edited onto several lines
    text = "\n".join(body_lines).strip()
    if not path or not text:
        return None
    return LedgerComment(path=path, line=line_no, body=text)


def parse_ledger(text: str) -> tuple[str, list[LedgerEntry]]:
    """Parse the pending-publication document into its PR sections.

    Returns (date, entries). A section spans from its `## PR #n` heading to
    the next such heading (or end of file); `entry.raw` is that exact span
    so consumed sections can be deleted byte-identically.
    """
    lines = text.splitlines()
    date = ""
    entries: list[LedgerEntry] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m0 = re.search(r"#\s*Pending PR Review Publication\s*[—-]\s*(\S+)", line)
        if m0 and not date:
            date = m0.group(1)
            i += 1
            continue
        m = re.match(r"##\s*PR\s*#(\d+)\s*(.*)", line)
        if not m:
            i += 1
            continue
        sec_start = i
        pr_number = int(m.group(1))
        rest = m.group(2).strip().lstrip("—-").strip()
        title, author = rest, ""
        m2 = re.search(r"\s*[—-]\s*@(\S+)\s*$", rest)
        if m2:
            author = m2.group(1)
            title = rest[: m2.start()].strip()
        entry = LedgerEntry(pr_number=pr_number, title=title, author=author)
        i += 1
        while i < len(lines) and not re.match(r"##\s*PR\s*#", lines[i]):
            raw = lines[i]
            if raw.startswith("url:"):
                entry.url = raw[len("url:") :].strip()
            elif raw.startswith("head:"):
                entry.head_oid = raw[len("head:") :].strip()
            elif raw.startswith("event:"):
                entry.event = raw[len("event:") :].strip()
            elif raw.startswith("verdict:"):
                entry.verdict = raw[len("verdict:") :].strip()
            elif raw.startswith("lang-note:"):
                entry.lang_warning = True
            elif raw == "body:":
                entry.body, i = _read_fence(lines, i + 1)
                continue
            elif raw == "inline:":
                i += 1
                while i < len(lines) and lines[i].startswith("```comment"):
                    block, i = _read_fence(lines, i)
                    comment = _parse_comment_block(block)
                    if comment:
                        entry.comments.append(comment)
                continue
            i += 1
        sec_end = i
        entry.raw = "\n".join(lines[sec_start:sec_end])
        entries.append(entry)
    return date, entries


def _gh_login() -> str:
    """The gh account the reviews are submitted as; empty when unknown."""
    try:
        return _run_gh("api", "user", "--jq", ".login").strip()
    except (subprocess.CalledProcessError, json.JSONDecodeError):
        return ""


def _payload_for_entry(
    entry: LedgerEntry, added: dict[str, set[int]], login: str
) -> tuple[dict | None, list[str]]:
    """Build the create-review REST payload for one ledger section.

    Returns (payload, skipped_reasons): payload None means the section is
    invalid (unknown event, empty body). The draft supplies `COMMENT`
    events; a `REQUEST_CHANGES` line in the ledger is only ever a deliberate
    user edit, and a self-authored PR is downgraded to COMMENT regardless.
    Inline comments are anchored to ADDED lines of the PR's current diff;
    anything else is reported as skipped instead of posted at a wrong place.
    """
    event = entry.event.strip() or "COMMENT"
    if event not in ("REQUEST_CHANGES", "COMMENT"):
        return None, [f"invalid event: {event!r}"]
    skipped: list[str] = []
    body = entry.body
    if event == "REQUEST_CHANGES" and not body.strip():
        body = "Changes requested."
    comments: list[dict] = []
    for c in entry.comments:
        if not c.body.strip():
            skipped.append(f"#{c.path}:{c.line} dropped (empty body)")
            continue
        if c.path in added and c.line in added[c.path]:
            comments.append(
                {"path": c.path, "line": c.line, "side": "RIGHT", "body": c.body}
            )
        else:
            skipped.append(f"#{c.path}:{c.line} dropped (not an added line)")
    if entry.author and entry.author == login:
        event = "COMMENT"  # GitHub forbids requesting changes on your own PR
        skipped.append("self-authored: downgraded to COMMENT")
    return {
        "commit_id": entry.head_oid or None,
        "event": event,
        "body": body,
        "comments": comments,
    }, skipped


def _post_review(pr_number: int, payload: dict) -> str:
    """Submit one GitHub review; returns its review_url on success."""
    payload = {k: v for k, v in payload.items() if v is not None}
    payload_file = PR_REVIEW_WORKSPACE_ROOT / f"pr_{pr_number}_review_payload.json"
    payload_file.parent.mkdir(parents=True, exist_ok=True)
    payload_file.write_text(json.dumps(payload), encoding="utf-8")
    out = _run_gh(
        "api",
        "--method",
        "POST",
        f"repos/{REPO}/pulls/{pr_number}/reviews",
        "--input",
        str(payload_file),
    )
    data = json.loads(out)
    return data.get("html_url", "")


def publish_from_ledger(
    workspace: Path | str | None = None, ledger_path: Path | str | None = None
) -> dict:
    """Publish after user approval: one GitHub review per ledger section.

    Every section is read back from the document, validated against the PR's
    current head, and submitted; only then is the PR archived, removed from
    pending, and its section deleted from the document. Sections that could
    not be submitted stay in place, so a rerun retries exactly the remainder
    (the documented residual risk: re-posting one review after a mid-step
    crash).
    """
    ws = Path(workspace) if workspace else PR_REVIEW_WORKSPACE_ROOT
    path = Path(ledger_path) if ledger_path else pending_publication_path(ws)
    if not path.exists():
        return {
            "status": "done",
            "outcomes": [],
            "message": "No pending-publication document to publish.",
        }
    date_str, entries = parse_ledger(path.read_text(encoding="utf-8"))
    date_str = date_str or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    login = _gh_login()
    outcomes: list[dict] = []
    consumed: set[int] = set()
    for entry in entries:
        outcome: dict = {
            "pr_number": entry.pr_number,
            "event": entry.event,
        }
        try:
            info = gh_pr_info(entry.pr_number)
            if info is None:
                outcome["error"] = "metadata_fetch_failed"
            elif info["state"] != "OPEN":
                note = f"not_open ({info['state']}) at publish time"
                outcome["review_url"] = ""
                outcome["note"] = note
                archive_record(entry, date_str, "", note)
                consumed.add(entry.pr_number)
            elif (
                info["head_oid"]
                and entry.head_oid
                and info["head_oid"] != entry.head_oid
            ):
                outcome["error"] = "head_moved"
            else:
                outcome.update(_submit_entry(entry, login))
                if not outcome.get("error"):
                    archive_record(entry, date_str, outcome["review_url"], "")
                    consumed.add(entry.pr_number)
        except subprocess.CalledProcessError as exc:
            outcome["error"] = (
                f"gh_failed: {(getattr(exc, 'stderr', '') or '').strip()[:200]}"
            )
        outcomes.append(outcome)

    remaining = [e for e in entries if e.pr_number not in consumed]
    if remaining:
        path.write_text(render_ledger(date_str, remaining), encoding="utf-8")
    else:
        path.unlink(missing_ok=True)
    return {
        "status": "done",
        "date": date_str,
        "outcomes": outcomes,
        "posted": sum(1 for o in outcomes if o.get("review_url")),
        "remaining": len(remaining),
        "ledger_path": str(path),
    }


def _submit_entry(entry: LedgerEntry, login: str) -> dict:
    """Validate one section against the live diff and submit its review."""
    try:
        patch = _run_gh("pr", "diff", str(entry.pr_number), "--repo", REPO)
    except subprocess.CalledProcessError:
        return {"error": "diff_fetch_failed"}
    payload, skipped = _payload_for_entry(entry, added_line_map(patch), login)
    if payload is None:
        return {"error": "; ".join(skipped) or "invalid section"}
    review_url = _post_review(entry.pr_number, payload)
    result: dict = {
        "review_url": review_url,
        "comments": len(payload["comments"]),
    }
    if skipped:
        result["skipped"] = skipped
    return result


def archive_record(
    entry: LedgerEntry, date_str: str, review_url: str, note: str
) -> None:
    """Append one archived record for a PR whose review was (about to be)
    submitted or was discovered stale at publish time.

    The archived `verdict` is the semantic II.11 verdict carried by the
    ledger section — even though the posted review is a COMMENT event — so
    the re-admit watch keeps seeing the asks-for-fixes PRs.
    """
    archive_path = PR_REVIEW_WORKSPACE_ROOT / PR_REVIEWED_ARCHIVE_FILE
    archive = load_archive(archive_path)
    archive["records"].append(
        {
            **_archive_record_common(),
            "url": entry.url,
            "pr_number": entry.pr_number,
            "title": entry.title,
            "author": entry.author,
            "state": "OPEN",
            "date": date_str,
            "review_url": review_url,
            "status": "reviewed",
            "reason": note,
            "verdict": entry.verdict
            or (
                "ready_for_human_review"
                if entry.event == "COMMENT"
                else ""
            ),
            "head_oid": entry.head_oid,
            "findings_count": len(entry.comments),
            "all_clear": entry.event == "COMMENT" and not entry.comments,
            "summary": (entry.body or "").split("\n")[0][:300],
        }
    )
    archive["last_run"] = {"date": date_str, "ledger": PENDING_PUBLICATION_FILE}
    save_archive(archive, archive_path)
    remove = {entry.pr_number}
    save_pending([u for u in load_pending() if parse_pr_url(u) not in remove])
